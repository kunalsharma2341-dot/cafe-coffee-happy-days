window.foodPhotoFallback = function (img) {
  if (img.dataset.fallback) return;
  img.dataset.fallback = 'true';
  img.src = 'assets/cafe.webp';
  img.alt = 'Inside Cafe Coffee Happy Days';
  const caption = img.parentElement.querySelector('small,figcaption');
  if (caption) caption.textContent = 'Photo unavailable · showing the café instead';
};
document.addEventListener(
  'error',
  function (e) {
    if (e.target.matches?.('img[data-food-photo]')) window.foodPhotoFallback(e.target);
  },
  true,
);
